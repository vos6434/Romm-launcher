function sanitizePathPart(input: string): string {
  return input
    .replace(/[<>:"|?*\u0000-\u001F]/g, "_")
    .replace(/\s+/g, " ")
    .trim();
}

function normalizeRelativeDownloadPath(raw: string | undefined): string | undefined {
  if (!raw) return undefined;
  const normalized = raw.trim().replace(/\\/g, "/");
  if (!normalized) return undefined;
  const withoutDrive = normalized.replace(/^[A-Za-z]:\//, "").replace(/^\/+/, "");
  const parts = withoutDrive
    .split("/")
    .map((part) => part.trim())
    .filter((part) => part.length > 0 && part !== "." && part !== "..")
    .map(sanitizePathPart)
    .filter((part) => part.length > 0);
  if (parts.length === 0) return undefined;
  return parts.join("/");
}

function normalizePlatformPart(raw: string | undefined): string | undefined {
  if (!raw) return undefined;
  const cleaned = sanitizePathPart(raw)
    .toLowerCase()
    .replace(/\s+/g, "-")
    .replace(/[^a-z0-9._-]/g, "-")
    .replace(/-+/g, "-")
    .replace(/^[-.]+|[-.]+$/g, "");
  return cleaned || undefined;
}

function inferPlatformFromFileName(fileName: string | undefined): string | undefined {
  if (!fileName) return undefined;
  const i = fileName.lastIndexOf(".");
  if (i <= 0 || i >= fileName.length - 1) return undefined;
  const ext = fileName.slice(i + 1).trim().toLowerCase();
  if (!ext) return undefined;
  const generic = new Set([
    "zip",
    "7z",
    "rar",
    "tar",
    "gz",
    "bz2",
    "xz",
    "iso",
    "bin",
    "cue",
    "chd",
  ]);
  if (generic.has(ext)) return undefined;
  return normalizePlatformPart(ext);
}

function structuredRommRelativePath(
  rawRelative: string | undefined,
  platformHint: string | undefined,
  fileNameHint: string,
): string {
  const normalized = normalizeRelativeDownloadPath(rawRelative);
  const parts = normalized ? normalized.split("/") : [];
  const lower = parts.map((p) => p.toLowerCase());

  const fileName =
    sanitizePathPart(parts[parts.length - 1] ?? "") ||
    sanitizePathPart(fileNameHint) ||
    "game.rom";

  const romsIdx = lower.lastIndexOf("roms");
  let platformFromPath: string | undefined;
  if (romsIdx > 0) {
    platformFromPath = normalizePlatformPart(parts[romsIdx - 1]);
  }
  if (!platformFromPath && parts.length >= 2 && lower[0] === "romm") {
    platformFromPath = normalizePlatformPart(parts[1]);
  }
  if (!platformFromPath && parts.length >= 2) {
    platformFromPath = normalizePlatformPart(parts[0]);
  }

  const platform =
    normalizePlatformPart(platformHint) ||
    platformFromPath ||
    inferPlatformFromFileName(fileNameHint) ||
    "unknown";

  return `Romm/${platform}/roms/${fileName}`;
}

function gameDownloadRelativePath(game: RommGame): string {
  const fallbackName = sanitizePathPart(game.fileName ?? game.name) || `${game.key}.rom`;
  return structuredRommRelativePath(
    game.romRelativePath,
    game.platformSlug,
    fallbackName,
  );
}

function joinLocalPath(baseDir: string, relativePath: string): string {
  const base = baseDir.trim().replace(/[\\/]+$/, "");
  if (!base) return relativePath;

  const isWindowsBase = /^[A-Za-z]:[\\/]/.test(base) || base.startsWith("\\\\");
  const sep = isWindowsBase ? "\\" : "/";
  const normalizedRelative = isWindowsBase
    ? relativePath.replace(/\//g, "\\")
    : relativePath.replace(/\\/g, "/");

  return `${base}${sep}${normalizedRelative}`;
}

function joinLegacyWindowsPath(baseDir: string, relativePath: string): string {
  const base = baseDir.trim().replace(/[\\/]+$/, "");
  if (!base) return relativePath;
  return `${base}\\${relativePath.replace(/\//g, "\\")}`;
}

function isWindowsStylePath(path: string): boolean {
  const p = path.trim();
  if (!p) return false;
  return /^[A-Za-z]:[\\/]/.test(p) || p.startsWith("\\\\");
}

/** Track width: one centered slot is scaled (~1.05); matches `.collection-slot--focus`. */
function carouselTrackWidthPx(n: number, slotW: number, gap: number): number {
  if (n < 1) return 0;
  return (n - 1) * slotW + slotW * 1.05 + (n - 1) * gap;
}

/**
 * Half-width of the offset window [−r … +r] so an odd number of slots fits in `width`.
 */
function computeCarouselSlotRadius(width: number): number {
  if (!Number.isFinite(width) || width < 60) return 0;
  const slotW = estimateCollectionSlotWidthPx();
  const gap = estimateCollectionGapPx();
  const safety = 1.035;
  const budget = width * 0.998;
  let n = 1;
  const maxSlots = MAX_CAROUSEL_SLOT_RADIUS * 2 + 1;
  while (n + 2 <= maxSlots) {
    const next = n + 2;
    const raw = carouselTrackWidthPx(next, slotW, gap);
    if (raw * safety > budget) break;
    n = next;
  }
  return (n - 1) / 2;
}

async function fetchCollectionArrays(
  session: Session,
  virtualType: VirtualCollectionType,
): Promise<RommCollection[]> {
  const regularP = invoke<string>("romm_api_get", {
    apiBase: session.apiBase,
    accessToken: session.accessToken,
    path: "collections",
    query: null,
  });
  const smartP = invoke<string>("romm_api_get", {
    apiBase: session.apiBase,
    accessToken: session.accessToken,
    path: "collections/smart",
    query: null,
  });
  /** Autogenerated virtual groups — one IGDB bucket (`franchise` or `collection`). */
  const virtualP = invoke<string>("romm_api_get", {
    apiBase: session.apiBase,
    accessToken: session.accessToken,
    path: "collections/virtual",
    query: `type=${virtualType}`,
  });

  const [regOutcome, smartOutcome, virtOutcome] = await Promise.allSettled([
    regularP,
    smartP,
    virtualP,
  ]);

  const taggedRegular: RommCollection[] = [];
  if (regOutcome.status === "fulfilled") {
    try {
      const regular = JSON.parse(regOutcome.value) as RommCollection[];
      if (Array.isArray(regular)) {
        taggedRegular.push(...regular.map((c) => ({ ...c, is_smart: false })));
      }
    } catch {
      /* ignore malformed */
    }
  }

  const taggedSmart: RommCollection[] = [];
  if (smartOutcome.status === "fulfilled") {
    try {
      const smart = JSON.parse(smartOutcome.value) as RommCollection[];
      if (Array.isArray(smart)) {
        taggedSmart.push(...smart.map((c) => ({ ...c, is_smart: true })));
      }
    } catch {
      /* ignore malformed */
    }
  }

  const taggedVirtual: RommCollection[] = [];
  if (virtOutcome.status === "fulfilled") {
    try {
      const virtual = JSON.parse(virtOutcome.value) as Record<
        string,
        unknown
      >[];
      if (Array.isArray(virtual)) {
        for (const row of virtual) {
          const typeField =
            typeof row.type === "string" ? row.type : undefined;
          taggedVirtual.push({
            ...(row as unknown as RommCollection),
            is_smart: false,
            is_virtual: true,
            collection_type: typeField,
          });
        }
      }
    } catch {
      /* ignore malformed */
    }
  }

  const combined = [
    ...taggedRegular,
    ...taggedSmart,
    ...taggedVirtual,
  ].sort((a, b) =>
    a.name.localeCompare(b.name, undefined, { sensitivity: "base" }),
  );

  if (combined.length === 0) {
    if (regOutcome.status === "rejected") throw regOutcome.reason;
    if (virtOutcome.status === "rejected") throw virtOutcome.reason;
    if (smartOutcome.status === "rejected") throw smartOutcome.reason;
  }

  return combined;
}

