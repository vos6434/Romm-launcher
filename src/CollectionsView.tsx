function formatInvokeError(err: unknown): string {
  if (typeof err === "string") return err;
  if (err instanceof Error) return err.message;
  try {
    return JSON.stringify(err);
  } catch {
    return String(err);
  }
}

function firstCoverUrl(
  apiBase: string,
  paths: string[] | null | undefined,
): string | undefined {
  if (!paths?.length) return undefined;
  return rommAssetUrl(apiBase, paths[0]);
}

function coverForCollection(apiBase: string, c: RommCollection): string | undefined {
  return (
    rommAssetUrl(apiBase, c.path_cover_large) ??
    rommAssetUrl(apiBase, c.path_cover_small) ??
    firstCoverUrl(apiBase, c.path_covers_large) ??
    firstCoverUrl(apiBase, c.path_covers_small) ??
    rommAssetUrl(apiBase, c.url_cover ?? undefined)
  );
}

function coverForCarouselSlot(
  apiBase: string,
  c: RommCollection,
  gridCovers: Record<string, string | undefined>,
): string | undefined {
  const k = collectionRowKey(c);
  const idx = getCollectionPrefs(k).coverSteamIndex ?? -1;
  if (idx >= 0) {
    const g = gridCovers[k];
    if (g) return g;
  }
  return coverForCollection(apiBase, c);
}

function coverForGameCarouselSlot(
  game: RommGame,
  gridCovers: Record<string, string | undefined>,
): string | undefined {
  const idx = getGamePrefs(game.key, game.name).coverSteamIndex ?? -1;
  if (idx >= 0) {
    const g = gridCovers[game.key];
    if (g) return g;
  }
  return game.coverUrl;
}

/** First line under poster: min–max game release years from RomM `/roms` metadata. */
function metaPrimaryLine(
  resolved: string | undefined,
  spansLoading: boolean,
): string {
  if (resolved !== undefined) return resolved;
  if (spansLoading) return "…";
  return "—";
}

/** Match `.collection-slot` width: `clamp(100px, 14vw, 160px)` (vw = window). */
function estimateCollectionSlotWidthPx(): number {
  if (typeof window === "undefined") return 130;
  return Math.min(160, Math.max(100, window.innerWidth * 0.14));
}

/** Match `.collections-carousel-track` gap: `clamp(12px, 2.5vw, 28px)`. */
function estimateCollectionGapPx(): number {
  if (typeof window === "undefined") return 20;
  return Math.min(28, Math.max(12, window.innerWidth * 0.025));
}

