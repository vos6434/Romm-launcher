function formatInvokeError(err: unknown): string {
  if (typeof err === "string") return err;
  if (err instanceof Error) return err.message;
  try {
    return JSON.stringify(err);
  } catch {
    return String(err);
  }
}

function firstCoverUrl(
  apiBase: string,
  paths: string[] | null | undefined,
): string | undefined {
  if (!paths?.length) return undefined;
  return rommAssetUrl(apiBase, paths[0]);
}

function coverForCollection(apiBase: string, c: RommCollection): string | undefined {
  return (
    rommAssetUrl(apiBase, c.path_cover_large) ??
    rommAssetUrl(apiBase, c.path_cover_small) ??
    firstCoverUrl(apiBase, c.path_covers_large) ??
    firstCoverUrl(apiBase, c.path_covers_small) ??
    rommAssetUrl(apiBase, c.url_cover ?? undefined)
  );
}

/** First line under poster: min–max game release years from RomM `/roms` metadata. */
function metaPrimaryLine(
  resolved: string | undefined,
  spansLoading: boolean,
): string {
  if (resolved !== undefined) return resolved;
  if (spansLoading) return "…";
  return "—";
}

/** Match `.collection-slot` width: `clamp(100px, 14vw, 160px)` (vw = window). */
function estimateCollectionSlotWidthPx(): number {
  if (typeof window === "undefined") return 130;
  return Math.min(160, Math.max(100, window.innerWidth * 0.14));
}

/** Match `.collections-carousel-track` gap: `clamp(12px, 2.5vw, 28px)`. */
function estimateCollectionGapPx(): number {
  if (typeof window === "undefined") return 20;
  return Math.min(28, Math.max(12, window.innerWidth * 0.025));
}

const MAX_CAROUSEL_SLOT_RADIUS = 30;

/** Settings panel: IGDB collection, franchise, SteamGrid key, save. */
const SETTINGS_NAV_SLOTS = 4;

/** Track width: one centered slot is `scale(1.08)`; others stay base width. */
function carouselTrackWidthPx(n: number, slotW: number, gap: number): number {
  if (n < 1) return 0;
  return (n - 1) * slotW + slotW * 1.08 + (n - 1) * gap;
}

/**
 * Half-width of the offset window [−r … +r] so an odd number of slots fits in `width`.
 */
function computeCarouselSlotRadius(width: number): number {
  if (!Number.isFinite(width) || width < 60) return 0;
  const slotW = estimateCollectionSlotWidthPx();
  const gap = estimateCollectionGapPx();
  const safety = 1.035;
  const budget = width * 0.998;
  let n = 1;
  const maxSlots = MAX_CAROUSEL_SLOT_RADIUS * 2 + 1;
  while (n + 2 <= maxSlots) {
    const next = n + 2;
    const raw = carouselTrackWidthPx(next, slotW, gap);
    if (raw * safety > budget) break;
    n = next;
  }
  return (n - 1) / 2;
}

async function fetchCollectionArrays(
  session: Session,
  virtualType: VirtualCollectionType,
): Promise<RommCollection[]> {
  const regularP = invoke<string>("romm_api_get", {
    apiBase: session.apiBase,
    accessToken: session.accessToken,
    path: "collections",
    query: null,
  });
  const smartP = invoke<string>("romm_api_get", {
    apiBase: session.apiBase,
    accessToken: session.accessToken,
    path: "collections/smart",
    query: null,
  });
  /** Autogenerated virtual groups — one IGDB bucket (`franchise` or `collection`). */
  const virtualP = invoke<string>("romm_api_get", {
    apiBase: session.apiBase,
    accessToken: session.accessToken,
    path: "collections/virtual",
    query: `type=${virtualType}`,
  });

  const [regOutcome, smartOutcome, virtOutcome] = await Promise.allSettled([
    regularP,
    smartP,
    virtualP,
  ]);

  const taggedRegular: RommCollection[] = [];
  if (regOutcome.status === "fulfilled") {
    try {
      const regular = JSON.parse(regOutcome.value) as RommCollection[];
      if (Array.isArray(regular)) {
        taggedRegular.push(...regular.map((c) => ({ ...c, is_smart: false })));
      }
    } catch {
      /* ignore malformed */
    }
  }

  const taggedSmart: RommCollection[] = [];
  if (smartOutcome.status === "fulfilled") {
    try {
      const smart = JSON.parse(smartOutcome.value) as RommCollection[];
      if (Array.isArray(smart)) {
        taggedSmart.push(...smart.map((c) => ({ ...c, is_smart: true })));
      }
    } catch {
      /* ignore malformed */
    }
  }

  const taggedVirtual: RommCollection[] = [];
  if (virtOutcome.status === "fulfilled") {
    try {
      const virtual = JSON.parse(virtOutcome.value) as Record<
        string,
        unknown
      >[];
      if (Array.isArray(virtual)) {
        for (const row of virtual) {
          const typeField =
            typeof row.type === "string" ? row.type : undefined;
          taggedVirtual.push({
            ...(row as unknown as RommCollection),
            is_smart: false,
            is_virtual: true,
            collection_type: typeField,
          });
        }
      }
    } catch {
      /* ignore malformed */
    }
  }

  const combined = [
    ...taggedRegular,
    ...taggedSmart,
    ...taggedVirtual,
  ].sort((a, b) =>
    a.name.localeCompare(b.name, undefined, { sensitivity: "base" }),
  );

  if (combined.length === 0) {
    if (regOutcome.status === "rejected") throw regOutcome.reason;
    if (virtOutcome.status === "rejected") throw virtOutcome.reason;
    if (smartOutcome.status === "rejected") throw smartOutcome.reason;
  }

  return combined;
}

export function CollectionsView({ session, onLogout }: Props) {
  const { flavor: gamepadFlavor, gamepadConnected } = useGamepadInput();
  const tauriShell = isTauri();
  const showGamepadHints = tauriShell && gamepadConnected;

  const [virtualType, setVirtualType] = useState<VirtualCollectionType>(() =>
    loadVirtualCollectionType(),
  );
  const [settingsOpen, setSettingsOpen] = useState(false);
  const [items, setItems] = useState<RommCollection[]>([]);
  const [focusIndex, setFocusIndex] = useState(0);
  const [loading, setLoading] = useState(true);
  const [refreshing, setRefreshing] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [releaseLabels, setReleaseLabels] = useState<Record<string, string>>(
    {},
  );
  const [yearSpansLoading, setYearSpansLoading] = useState(false);
  const carouselViewportRef = useRef<HTMLDivElement>(null);
  const carouselTrackRef = useRef<HTMLDivElement>(null);
  const focusSlotRef = useRef<HTMLButtonElement | null>(null);
  const settingsWrapRef = useRef<HTMLDivElement>(null);
  const settingsRadioCollectionRef = useRef<HTMLInputElement>(null);
  const settingsRadioFranchiseRef = useRef<HTMLInputElement>(null);
  const settingsSteamKeyRef = useRef<HTMLInputElement>(null);
  const settingsSaveRef = useRef<HTMLButtonElement>(null);
  const [settingsNavIndex, setSettingsNavIndex] = useState(0);
  const [slotRadius, setSlotRadius] = useState(2);
  const [steamGridKeyDraft, setSteamGridKeyDraft] = useState(() =>
    loadSteamGridDbApiKey(),
  );
  const [steamSettingsRev, setSteamSettingsRev] = useState(0);

  useEffect(() => {
    let cancelled = false;
    (async () => {
      setLoading(true);
      setError(null);
      try {
        const list = await fetchCollectionArrays(session, virtualType);
        if (!cancelled) {
          setItems(list);
          setFocusIndex(0);
        }
      } catch (e) {
        if (!cancelled) setError(formatInvokeError(e));
      } finally {
        if (!cancelled) setLoading(false);
      }
    })();
    return () => {
      cancelled = true;
    };
  }, [session, virtualType]);

  useEffect(() => {
    if (loading || items.length === 0) {
      setReleaseLabels({});
      setYearSpansLoading(false);
      return;
    }
    let cancelled = false;
    setReleaseLabels({});
    setYearSpansLoading(true);
    void (async () => {
      await mapPool(items, FETCH_CONCURRENCY, async (c) => {
        const key = collectionRowKey(c);
        try {
          const label = await fetchReleaseYearLabel(session, c);
          if (!cancelled) {
            setReleaseLabels((prev) => ({ ...prev, [key]: label }));
          }
        } catch {
          if (!cancelled) {
            setReleaseLabels((prev) => ({ ...prev, [key]: "—" }));
          }
        }
      });
      if (!cancelled) setYearSpansLoading(false);
    })();
    return () => {
      cancelled = true;
      setYearSpansLoading(false);
    };
  }, [session, items, loading]);

  const onRefreshLibrary = useCallback(async () => {
    setRefreshing(true);
    setError(null);
    try {
      const list = await fetchCollectionArrays(session, virtualType);
      setItems(list);
      setFocusIndex((i) =>
        list.length === 0 ? 0 : Math.min(i, list.length - 1),
      );
    } catch (e) {
      setError(formatInvokeError(e));
    } finally {
      setRefreshing(false);
    }
  }, [session, virtualType]);

  const toggleSettings = useCallback(() => {
    setSettingsOpen((prev) => {
      if (!prev) {
        setSteamGridKeyDraft(loadSteamGridDbApiKey());
        setSettingsNavIndex(virtualType === "franchise" ? 1 : 0);
      }
      return !prev;
    });
  }, [virtualType]);

  const saveSteamGridKey = useCallback(() => {
    saveSteamGridDbApiKey(steamGridKeyDraft);
    setSteamSettingsRev((n) => n + 1);
  }, [steamGridKeyDraft]);

  const activateSettingsNav = useCallback(() => {
    switch (settingsNavIndex) {
      case 0:
        settingsRadioCollectionRef.current?.click();
        break;
      case 1:
        settingsRadioFranchiseRef.current?.click();
        break;
      case 2:
        settingsSteamKeyRef.current?.focus();
        break;
      case 3:
        saveSteamGridKey();
        break;
      default:
        break;
    }
  }, [settingsNavIndex, saveSteamGridKey]);

  useLayoutEffect(() => {
    if (!settingsOpen) return;
    const refs = [
      settingsRadioCollectionRef,
      settingsRadioFranchiseRef,
      settingsSteamKeyRef,
      settingsSaveRef,
    ] as const;
    const el = refs[settingsNavIndex]?.current;
    el?.focus();
  }, [settingsOpen, settingsNavIndex]);

  function selectVirtualType(next: VirtualCollectionType) {
    saveVirtualCollectionType(next);
    setVirtualType(next);
  }

  useEffect(() => {
    if (loading || items.length === 0) return;
    const el = carouselViewportRef.current;
    if (!el) return;
    const apply = () => {
      const t = carouselViewportRef.current;
      if (t) {
        setSlotRadius(computeCarouselSlotRadius(t.getBoundingClientRect().width));
      }
    };
    apply();
    const ro = new ResizeObserver(() => apply());
    ro.observe(el);
    window.addEventListener("resize", apply);
    return () => {
      ro.disconnect();
      window.removeEventListener("resize", apply);
    };
  }, [loading, items.length]);

  /** Keep the focused card’s horizontal center aligned with the viewport center. */
  useLayoutEffect(() => {
    const vp = carouselViewportRef.current;
    const track = carouselTrackRef.current;
    const focusEl = focusSlotRef.current;
    if (!vp || !track || !focusEl || loading || items.length === 0) {
      if (track) track.style.transform = "translateX(0)";
      return;
    }

    const align = () => {
      const vr = vp.getBoundingClientRect();
      const fr = focusEl.getBoundingClientRect();
      const dx = vr.left + vr.width / 2 - (fr.left + fr.width / 2);
      track.style.transform = `translateX(${dx}px)`;
    };

    align();
    const ro = new ResizeObserver(() => requestAnimationFrame(align));
    ro.observe(vp);
    ro.observe(track);
    return () => ro.disconnect();
  }, [focusIndex, items.length, loading, refreshing, slotRadius]);

  const focused = items[focusIndex];
  const cardCoverUrl = useMemo(
    () => (focused ? coverForCollection(session.apiBase, focused) : undefined),
    [focused, session.apiBase],
  );

  const [heroBg, setHeroBg] = useState<{
    key: string;
    url: string | undefined;
  } | null>(null);

  useEffect(() => {
    if (!focused) {
      setHeroBg(null);
      return;
    }
    const key = collectionRowKey(focused);
    const cover = coverForCollection(session.apiBase, focused);
    setHeroBg({ key, url: undefined });

    let cancelled = false;
    void (async () => {
      const url = await fetchCollectionBackgroundUrl(session, focused, cover);
      if (cancelled) return;
      setHeroBg({ key, url: url ?? undefined });
    })();

    return () => {
      cancelled = true;
    };
  }, [focused, session.apiBase, session.accessToken, steamSettingsRev]);

  const bgUrl =
    focused && heroBg && heroBg.key === collectionRowKey(focused)
      ? (heroBg.url ?? cardCoverUrl)
      : cardCoverUrl;

  const moveFocus = useCallback(
    (delta: number) => {
      if (items.length === 0) return;
      setFocusIndex((i) => {
        const n = items.length;
        return (i + delta + n) % n;
      });
    },
    [items.length],
  );

  const hintsReady = !loading;
  const showMoveHints = hintsReady && items.length > 0;

  useCollectionsGamepadNavigation({
    enabled: tauriShell && hintsReady,
    itemsLength: items.length,
    settingsOpen,
    settingsNav: settingsOpen
      ? {
          slotCount: SETTINGS_NAV_SLOTS,
          setFocusIndex: setSettingsNavIndex,
          onActivate: activateSettingsNav,
          onCloseSettings: () => setSettingsOpen(false),
        }
      : null,
    refreshDisabled: loading || refreshing,
    onMove: moveFocus,
    onBack: onLogout,
    onToggleSettings: toggleSettings,
    onRefresh: () => void onRefreshLibrary(),
  });

  useEffect(() => {
    function isShortcutTarget(el: EventTarget | null): boolean {
      if (!el || !(el instanceof HTMLElement)) return false;
      const tag = el.tagName;
      if (tag === "INPUT" || tag === "TEXTAREA" || tag === "SELECT") {
        return true;
      }
      return el.isContentEditable;
    }

    function onKey(e: KeyboardEvent) {
      if (e.key === "Escape") {
        if (settingsOpen) {
          e.preventDefault();
          setSettingsOpen(false);
          return;
        }
        e.preventDefault();
        onLogout();
        return;
      }

      if (!isShortcutTarget(e.target)) {
        if (e.key === "o" || e.key === "O") {
          e.preventDefault();
          toggleSettings();
          return;
        }
        if (
          (e.key === "r" || e.key === "R") &&
          !loading &&
          !refreshing
        ) {
          e.preventDefault();
          void onRefreshLibrary();
          return;
        }
      }

      if (settingsOpen) {
        if (e.key === "ArrowUp") {
          e.preventDefault();
          setSettingsNavIndex((i) => Math.max(0, i - 1));
          return;
        }
        if (e.key === "ArrowDown") {
          e.preventDefault();
          setSettingsNavIndex((i) =>
            Math.min(SETTINGS_NAV_SLOTS - 1, i + 1),
          );
          return;
        }
        if (e.key === "Enter" && !e.repeat) {
          if (e.target instanceof HTMLTextAreaElement) return;
          e.preventDefault();
          activateSettingsNav();
          return;
        }
        if (e.key === "ArrowLeft" || e.key === "ArrowRight") {
          e.preventDefault();
          return;
        }
        if (e.key === "Backspace" && !isShortcutTarget(e.target)) {
          e.preventDefault();
          return;
        }
        return;
      }

      if (e.key === "ArrowLeft") {
        e.preventDefault();
        moveFocus(-1);
      } else if (e.key === "ArrowRight") {
        e.preventDefault();
        moveFocus(1);
      } else if (e.key === "Backspace") {
        e.preventDefault();
        onLogout();
      }
    }
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [
    moveFocus,
    onLogout,
    onRefreshLibrary,
    settingsOpen,
    toggleSettings,
    activateSettingsNav,
    loading,
    refreshing,
    items,
    focusIndex,
  ]);

  const slots = useMemo(() => {
    const r = slotRadius;
    const len = r * 2 + 1;
    return Array.from({ length: len }, (_, i) => i - r);
  }, [slotRadius]);

  const settingsPortal =
    settingsOpen && typeof document !== "undefined"
      ? createPortal(
          <>
            <div
              className="collections-settings-backdrop"
              aria-hidden
              onPointerDown={() => setSettingsOpen(false)}
            />
            <div
              ref={settingsWrapRef}
              id="collections-settings-menu"
              className="collections-settings-menu collections-settings-menu--popover"
              role="dialog"
              aria-label="Collection settings"
              aria-modal="true"
              onPointerDown={(e) => e.stopPropagation()}
            >
              <p className="collections-settings-menu-title">
                Autogenerated groups
              </p>
              <p className="collections-settings-menu-hint">
                Same option as RomM’s virtual collection type (IGDB metadata).
              </p>
              <label
                className={`collections-settings-option${settingsNavIndex === 0 ? " collections-settings-option--active" : ""}`}
              >
                <input
                  ref={settingsRadioCollectionRef}
                  type="radio"
                  name="virtual-type"
                  checked={virtualType === "collection"}
                  onChange={() => selectVirtualType("collection")}
                  onFocus={() => setSettingsNavIndex(0)}
                />
                <span>
                  <strong>IGDB collection</strong>
                  <span className="collections-settings-option-desc">
                    Series / collection names from IGDB (RomM default).
                  </span>
                </span>
              </label>
              <label
                className={`collections-settings-option${settingsNavIndex === 1 ? " collections-settings-option--active" : ""}`}
              >
                <input
                  ref={settingsRadioFranchiseRef}
                  type="radio"
                  name="virtual-type"
                  checked={virtualType === "franchise"}
                  onChange={() => selectVirtualType("franchise")}
                  onFocus={() => setSettingsNavIndex(1)}
                />
                <span>
                  <strong>Franchise</strong>
                  <span className="collections-settings-option-desc">
                    Group by franchise (e.g. Super Mario).
                  </span>
                </span>
              </label>
              <div className="collections-settings-steamgrid">
                <p className="collections-settings-menu-title collections-settings-menu-title--spaced">
                  SteamGridDB backgrounds
                </p>
                <p className="collections-settings-menu-hint">
                  Optional API key for hero-style backdrop art (
                  <a
                    href="https://www.steamgriddb.com/profile/preferences"
                    target="_blank"
                    rel="noreferrer"
                  >
                    create a key
                  </a>
                  ). Stored only on this device. If empty, RomM screenshots are
                  used instead.
                </p>
                <input
                  ref={settingsSteamKeyRef}
                  type="password"
                  className={`collections-settings-steamgrid-input${settingsNavIndex === 2 ? " collections-settings-steamgrid-input--active" : ""}`}
                  autoComplete="off"
                  placeholder="API key"
                  value={steamGridKeyDraft}
                  onChange={(e) => setSteamGridKeyDraft(e.target.value)}
                  onFocus={() => setSettingsNavIndex(2)}
                />
                <button
                  ref={settingsSaveRef}
                  type="button"
                  className={`collections-settings-steamgrid-save${settingsNavIndex === 3 ? " collections-settings-steamgrid-save--active" : ""}`}
                  onClick={saveSteamGridKey}
                  onFocus={() => setSettingsNavIndex(3)}
                >
                  Save key
                </button>
              </div>
            </div>
          </>,
          document.body,
        )
      : null;

  return (
    <div className="collections-screen">
      {settingsPortal}

      <div
        className="collections-bg"
        style={
          bgUrl
            ? {
                backgroundImage: `url("${bgUrl.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}")`,
              }
            : undefined
        }
      />
      <div className="collections-bg-scrim" />

      <header className="collections-header">
        <h1 className="collections-title">COLLECTIONS</h1>
        <p className="collections-subtitle">Browse your game collections</p>
      </header>

      {loading ? (
        <p className="collections-status">Loading collections…</p>
      ) : null}
      {error ? (
        <p className="collections-error" role="alert">
          {error}
        </p>
      ) : null}

      {!loading && !error && items.length === 0 ? (
        <p className="collections-status">
          No collections found. Add manual or smart collections in RomM, or
          enable autogenerated groups in library settings—then log in again.
        </p>
      ) : null}

      {!loading && items.length > 0 ? (
        <div
          className="collections-carousel-viewport"
          ref={carouselViewportRef}
        >
          <div
            className="collections-carousel-track"
            ref={carouselTrackRef}
            role="list"
          >
            {slots.map((offset) => {
              const idx = focusIndex + offset;
              const c = items[idx];
              const isFocus = offset === 0;
              const isPlaceholder = idx < 0 || idx >= items.length;
              const edgeClass =
                slots.length > 1
                  ? offset === -slotRadius
                    ? " collection-slot--edge-start"
                    : offset === slotRadius
                      ? " collection-slot--edge-end"
                      : ""
                  : "";

              if (isPlaceholder) {
                return (
                  <div
                    key={`empty-${offset}`}
                    className={`collection-slot collection-slot--empty${edgeClass}`}
                    aria-hidden
                  >
                    <div className="collection-poster collection-poster--empty" />
                    <div className="collection-meta">
                      <span className="collection-years"> </span>
                      <span className="collection-label"> </span>
                    </div>
                  </div>
                );
              }

              const cover = coverForCollection(session.apiBase, c);
              return (
                <button
                  key={`${collectionRowKey(c)}-${idx}`}
                  ref={isFocus ? focusSlotRef : undefined}
                  type="button"
                  role="listitem"
                  className={`collection-slot${isFocus ? " collection-slot--focus" : ""}${edgeClass}`}
                  onClick={() => setFocusIndex(idx)}
                >
                <div
                  className={`collection-poster${isFocus ? " collection-poster--focus" : ""}`}
                >
                  {cover ? (
                    <img src={cover} alt="" loading="lazy" />
                  ) : (
                    <span className="collection-poster-fallback">{c.name}</span>
                  )}
                </div>
                <div className="collection-meta">
                  <span className="collection-years">
                    {metaPrimaryLine(
                      releaseLabels[collectionRowKey(c)],
                      yearSpansLoading,
                    )}
                  </span>
                  <span className="collection-label">{c.name}</span>
                </div>
                </button>
              );
            })}
          </div>
        </div>
      ) : null}

      {hintsReady ? (
        <footer className="collections-footer" aria-label="Shortcuts">
          {showMoveHints ? (
            <div className="collections-footer-hint">
              {showGamepadHints ? (
                <GamepadHorizontalNavPromptGlyphs flavor={gamepadFlavor} />
              ) : (
                <KeyboardMoveHorizontalGlyph />
              )}
              <span>Move</span>
            </div>
          ) : null}
          <div className="collections-footer-hint">
            {showGamepadHints ? (
              <GamepadStartPromptGlyph flavor={gamepadFlavor} />
            ) : (
              <KeyboardSettingsGlyph />
            )}
            <span>Settings</span>
          </div>
          <div
            className={`collections-footer-hint${loading || refreshing ? " collections-footer-hint--disabled" : ""}`}
          >
            {showGamepadHints ? (
              <GamepadSelectPromptGlyph flavor={gamepadFlavor} />
            ) : (
              <KeyboardRefreshGlyph />
            )}
            <span>{refreshing ? "Refreshing…" : "Refresh library"}</span>
          </div>
          <div className="collections-footer-hint">
            {showGamepadHints ? (
              <GamepadPromptGlyph flavor={gamepadFlavor} role="back" />
            ) : (
              <KeyboardBackGlyph />
            )}
            <span>Back to login</span>
          </div>
        </footer>
      ) : null}
    </div>
  );
}
