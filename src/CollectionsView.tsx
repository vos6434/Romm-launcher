/**
 * Signed minimal index delta on the ring → slide direction.
 * (The old “forward modular distance ≤ n/2” rule breaks for n=2: both steps are length 1
 * but left must be “prev”, not “next”.)
 */
function focusNavSlideDir(from: number, to: number, len: number): "next" | "prev" {
  if (len <= 1) return "next";
  let d = to - from;
  if (d > len / 2) d -= len;
  if (d < -len / 2) d += len;
  return d > 0 ? "next" : "prev";
}

type CarouselTransition = { dir: "next" | "prev"; from: number; to: number };

function carouselSlotContentAnimClass(
  t: CarouselTransition | null,
  p: {
    idx: number;
    offset: number;
    isFocus: boolean;
    isPlaceholder: boolean;
    slotRadius: number;
  },
): string {
  if (!t || p.isPlaceholder) return "";
  if (p.isFocus) {
    return t.dir === "next"
      ? " collection-slot-content--slide-next"
      : " collection-slot-content--slide-prev";
  }
  if (p.idx === t.from) {
    return t.dir === "next"
      ? " collection-slot-content--leave-next"
      : " collection-slot-content--leave-prev";
  }
  const r = p.slotRadius;
  if (r > 0) {
    if (t.dir === "next" && p.offset === r) {
      return " collection-slot-content--enter-next";
    }
    if (t.dir === "prev" && p.offset === -r) {
      return " collection-slot-content--enter-prev";
    }
  }
  return "";
}

function backgroundImageStyle(url: string | undefined): CSSProperties | undefined {
  if (!url) return undefined;
  return {
    backgroundImage: `url("${url.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}")`,
  };
}

/** Track width: one centered slot is scaled (~1.05); matches `.collection-slot--focus`. */
function carouselTrackWidthPx(n: number, slotW: number, gap: number): number {
  if (n < 1) return 0;
  return (n - 1) * slotW + slotW * 1.05 + (n - 1) * gap;
}

/**
 * Half-width of the offset window [−r … +r] so an odd number of slots fits in `width`.
 */
function computeCarouselSlotRadius(width: number): number {
  if (!Number.isFinite(width) || width < 60) return 0;
  const slotW = estimateCollectionSlotWidthPx();
  const gap = estimateCollectionGapPx();
  const safety = 1.035;
  const budget = width * 0.998;
  let n = 1;
  const maxSlots = MAX_CAROUSEL_SLOT_RADIUS * 2 + 1;
  while (n + 2 <= maxSlots) {
    const next = n + 2;
    const raw = carouselTrackWidthPx(next, slotW, gap);
    if (raw * safety > budget) break;
    n = next;
  }
  return (n - 1) / 2;
}

async function fetchCollectionArrays(
  session: Session,
  virtualType: VirtualCollectionType,
): Promise<RommCollection[]> {
  const regularP = invoke<string>("romm_api_get", {
    apiBase: session.apiBase,
    accessToken: session.accessToken,
    path: "collections",
    query: null,
  });
  const smartP = invoke<string>("romm_api_get", {
    apiBase: session.apiBase,
    accessToken: session.accessToken,
    path: "collections/smart",
    query: null,
  });
  /** Autogenerated virtual groups — one IGDB bucket (`franchise` or `collection`). */
  const virtualP = invoke<string>("romm_api_get", {
    apiBase: session.apiBase,
    accessToken: session.accessToken,
    path: "collections/virtual",
    query: `type=${virtualType}`,
  });

  const [regOutcome, smartOutcome, virtOutcome] = await Promise.allSettled([
    regularP,
    smartP,
    virtualP,
  ]);

  const taggedRegular: RommCollection[] = [];
  if (regOutcome.status === "fulfilled") {
    try {
      const regular = JSON.parse(regOutcome.value) as RommCollection[];
      if (Array.isArray(regular)) {
        taggedRegular.push(...regular.map((c) => ({ ...c, is_smart: false })));
      }
    } catch {
      /* ignore malformed */
    }
  }

  const taggedSmart: RommCollection[] = [];
  if (smartOutcome.status === "fulfilled") {
    try {
      const smart = JSON.parse(smartOutcome.value) as RommCollection[];
      if (Array.isArray(smart)) {
        taggedSmart.push(...smart.map((c) => ({ ...c, is_smart: true })));
      }
    } catch {
      /* ignore malformed */
    }
  }

  const taggedVirtual: RommCollection[] = [];
  if (virtOutcome.status === "fulfilled") {
    try {
      const virtual = JSON.parse(virtOutcome.value) as Record<
        string,
        unknown
      >[];
      if (Array.isArray(virtual)) {
        for (const row of virtual) {
          const typeField =
            typeof row.type === "string" ? row.type : undefined;
          taggedVirtual.push({
            ...(row as unknown as RommCollection),
            is_smart: false,
            is_virtual: true,
            collection_type: typeField,
          });
        }
      }
    } catch {
      /* ignore malformed */
    }
  }

  const combined = [
    ...taggedRegular,
    ...taggedSmart,
    ...taggedVirtual,
  ].sort((a, b) =>
    a.name.localeCompare(b.name, undefined, { sensitivity: "base" }),
  );

  if (combined.length === 0) {
    if (regOutcome.status === "rejected") throw regOutcome.reason;
    if (virtOutcome.status === "rejected") throw virtOutcome.reason;
    if (smartOutcome.status === "rejected") throw smartOutcome.reason;
  }

  return combined;
}

